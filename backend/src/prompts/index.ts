export function buildUserPrompt(form: {
  ageGroup: string;
  role: string;
  topic: string;
  description: string;
  goals: string[];
  clarification?: string;
}): string {
  const parts = [
    `Возрастная группа: ${form.ageGroup}`,
    `Роль: ${form.role}`,
    `Тема: ${form.topic}`,
    `Суть ситуации: ${form.description}`,
    `Запрошенные цели: ${form.goals.join(', ')}`,
  ];

  if (form.clarification) {
    parts.push(`Уточнение от пользователя: ${form.clarification}`);
  }

  return parts.join('\n');
}
